#!/usr/bin/env python3
"""Writes the LCD UI's fonts: components/hmi_ui/ui_fonts.h and ui_fonts_data.cpp.

  tools/gen_ui_fonts.py            (run with a Python that has Pillow, e.g. ~/esphome/venv/bin/python)

Each font in FONTS below is one TTF from fonts/ at one size with one set of characters. A glyph
is stored as a 4-bit alpha bitmap, which the canvas blends onto the frame, so text has smooth
edges on the display and in the simulator alike. Big sizes list only the characters they are
used for: an 80 px digit is about 1.5 kB.
"""

import sys
from pathlib import Path

from PIL import ImageFont

REPO = Path(__file__).resolve().parent.parent
FONT_DIR = REPO / "fonts"
OUT_H = REPO / "components" / "hmi_ui" / "ui_fonts.h"
OUT_CPP = REPO / "components" / "hmi_ui" / "ui_fonts_data.cpp"

ASCII = "".join(chr(c) for c in range(32, 127))
# Beyond ASCII: units and marks the screens use. Ones a font lacks are left out.
EXTRA = "°Ωµ±·–−×≈≤≥Δ←→↑↓‹›…"
TEXT = ASCII + EXTRA
# For the big numbers
DIGITS = "0123456789.,:-+% kWVAhmC°"
# For the biggest: digits alone (a 128 px digit is about 3 kB)
BARE_DIGITS = "0123456789.-+"

# name, file, pixel size, characters
FONTS = [
    ("R14", "Roboto-Regular.ttf", 14, TEXT),
    ("R16", "Roboto-Regular.ttf", 16, TEXT),
    ("R18", "Roboto-Regular.ttf", 18, TEXT),
    ("R20", "Roboto-Regular.ttf", 20, TEXT),
    ("R24", "Roboto-Regular.ttf", 24, TEXT),
    ("R32", "Roboto-Regular.ttf", 32, TEXT),
    ("M16", "Roboto-Medium.ttf", 16, TEXT),
    ("M20", "Roboto-Medium.ttf", 20, TEXT),
    ("M24", "Roboto-Medium.ttf", 24, TEXT),
    ("M32", "Roboto-Medium.ttf", 32, TEXT),
    ("M48", "Roboto-Medium.ttf", 48, DIGITS),
    ("M72", "Roboto-Medium.ttf", 72, DIGITS),
    ("M128", "Roboto-Medium.ttf", 128, BARE_DIGITS),
    ("B20", "Roboto-Bold.ttf", 20, TEXT),
    ("MONO14", "RobotoMono-Regular.ttf", 14, TEXT),
]


def glyphs_of(path, size, chars):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    missing = bytes(font.getmask(chr(0xFFFF), mode="L"))
    out = []
    for ch in sorted(set(chars)):
        cp = ord(ch)
        mask = font.getmask(ch, mode="L")
        if cp > 126 and bytes(mask) == missing:
            continue  # the font has no such character
        w, h = mask.size
        left, top, _right, _bottom = font.getbbox(ch, anchor="ls") if w and h else (0, 0, 0, 0)
        advance = round(font.getlength(ch))
        rows = bytearray()
        data = bytes(mask)
        for y in range(h):
            row = [min(15, (v + 8) // 17) for v in data[y * w:(y + 1) * w]]
            if len(row) % 2:
                row.append(0)
            rows += bytes((row[i] << 4) | row[i + 1] for i in range(0, len(row), 2))
        if not (w < 256 and h < 256 and -128 <= left < 128 and -128 <= -top < 128 and advance < 256):
            sys.exit(f"{path.name} {size}: glyph {ch!r} doesn't fit the Glyph fields")
        out.append((cp, w, h, left, -top, advance, bytes(rows)))
    return ascent, descent, out


def main():
    header = [
        "// Generated by tools/gen_ui_fonts.py from the TTF files in fonts/. Do not edit.",
        "#pragma once",
        "",
        '#include "ui_canvas.h"',
        "",
        "namespace hmiui {",
        "",
    ]
    source = [
        "// Generated by tools/gen_ui_fonts.py from the TTF files in fonts/. Do not edit.",
        '#include "ui_fonts.h"',
        "",
        "namespace hmiui {",
        "",
    ]
    total = 0
    for name, file, size, chars in FONTS:
        ascent, descent, glyphs = glyphs_of(FONT_DIR / file, size, chars)
        alpha = bytearray()
        table = []
        for cp, w, h, left, top, advance, rows in glyphs:
            table.append(f"    {{{len(alpha)}, {w}, {h}, {left}, {top}, {advance}}},")
            alpha += rows
        total += len(alpha) + 12 * len(glyphs)
        header.append(f"extern const Font FONT_{name};  // {file[:-4]} {size} px, {len(glyphs)} characters")
        source.append(f"static const uint16_t {name}_CP[] = {{{', '.join(str(g[0]) for g in glyphs)}}};")
        source.append(f"static const Glyph {name}_GLYPHS[] = {{")
        source += table
        source.append("};")
        source.append(f"static const uint8_t {name}_ALPHA[] = {{")
        for i in range(0, len(alpha), 32):
            source.append("    " + ",".join(str(b) for b in alpha[i:i + 32]) + ",")
        source.append("};")
        source.append(
            f"const Font FONT_{name} = {{{size}, {ascent}, {descent}, {len(glyphs)}, "
            f"{name}_CP, {name}_GLYPHS, {name}_ALPHA}};"
        )
        source.append("")
        print(f"{name}: {file} {size} px, {len(glyphs)} characters, {len(alpha)} bytes")
    header += ["", "}  // namespace hmiui", ""]
    source += ["}  // namespace hmiui", ""]
    OUT_H.write_text("\n".join(header), encoding="utf-8", newline="\n")
    OUT_CPP.write_text("\n".join(source), encoding="utf-8", newline="\n")
    print(f"total about {total // 1024} kB of font data")


if __name__ == "__main__":
    main()
