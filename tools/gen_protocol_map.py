#!/usr/bin/env python3
"""Writes the HMI protocol map from the BMS firmware's own headers.

  tools/gen_protocol_map.py <bmstest1 checkout>          rewrite the generated files
  tools/gen_protocol_map.py <bmstest1 checkout> --check  fail if they differ from the headers

The register IDs, types and flags, the event list and the array IDs are read from
bms/protocols/hmi_serial/hmi_serial.h, hmi_registers.c, hmi_arrays.h and bms/sys/events/events.h,
and written to components/hmi_bms/hmi_map.h (for the component) and hmi_map.py (for its ESPHome
schema). Nothing in this repo copies an ID or an event name by hand.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT_H = REPO / "components" / "hmi_bms" / "hmi_map.h"
OUT_PY = REPO / "components" / "hmi_bms" / "hmi_map.py"

TYPES = {
    "UINT8": 0x11,
    "INT8": 0x21,
    "UINT16": 0x12,
    "INT16": 0x22,
    "UINT32": 0x14,
    "INT32": 0x24,
    "UINT64": 0x18,
    "INT64": 0x28,
    "FLOAT": 0x34,
    "DOUBLE": 0x38,
}
FLAG_WRITABLE = 0x01
FLAG_SAVED = 0x02


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def parse(fw):
    hmi = fw / "bms" / "protocols" / "hmi_serial"
    serial_h = read(hmi / "hmi_serial.h")
    registers_c = read(hmi / "hmi_registers.c")
    arrays_h = read(hmi / "hmi_arrays.h")
    events_h = read(fw / "bms" / "sys" / "events" / "events.h")

    version = int(re.search(r"#define HMI_PROTOCOL_VERSION\s+(\d+)", serial_h).group(1))

    ids = {}
    for m in re.finditer(r"^#define HMI_REG_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b", serial_h, re.M):
        if not m.group(1).startswith("FLAG_"):
            ids[m.group(1)] = int(m.group(2), 0)

    # The table in hmi_registers.c has each register's type and flags (W, WS or 0)
    registers = []
    for m in re.finditer(r"\{\s*HMI_REG_(\w+)\s*,\s*HMI_TYPE_(\w+)\s*,\s*(\w+)\s*\}", registers_c):
        name, type_, flags = m.groups()
        if flags not in ("0", "W", "WS"):
            sys.exit(f"hmi_registers.c: unknown flags {flags!r} on {name}")
        value = {"0": 0, "W": FLAG_WRITABLE, "WS": FLAG_WRITABLE | FLAG_SAVED}[flags]
        registers.append((name, ids[name], TYPES[type_], value))
    missing = sorted(set(ids) - {r[0] for r in registers})
    if missing:
        sys.exit(f"registers defined in hmi_serial.h but not in the hmi_registers.c table: {missing}")
    if [r[1] for r in registers] != sorted(r[1] for r in registers):
        sys.exit("hmi_registers.c: the table is not in increasing ID order")

    messages = {}
    for m in re.finditer(r"^#define HMI_MSG_(\w+)\s+(0x[0-9A-Fa-f]+)\b", serial_h, re.M):
        messages[m.group(1)] = int(m.group(2), 16)

    arrays = {}
    for m in re.finditer(r"^#define HMI_ARRAY_(\w+)\s+(\d+)\s*//", arrays_h, re.M):
        if m.group(1) not in ("ENCODING_NONE", "RESPONSE_HEADER_LEN", "WRITE_HEADER_LEN"):
            arrays[m.group(1)] = int(m.group(2))

    block = re.search(r"#define EVENT_TYPES\(X\)(.*?)\n\n", events_h, re.S).group(1)
    events = re.findall(r"\bX\((\w+)\s*,", block)

    commit = subprocess.run(
        ["git", "-c", "core.autocrlf=true", "log", "-1", "--format=%h", "--",
         "bms/protocols/hmi_serial", "bms/sys/events/events.h"],
        cwd=fw, capture_output=True, text=True,
    ).stdout.strip() or "unknown"
    return version, registers, messages, arrays, events, commit


def render(version, registers, messages, arrays, events, commit):
    head = (
        "Generated by tools/gen_protocol_map.py from the BMS firmware (bmstest1), last protocol\n"
        f"change {commit}. Do not edit: change the firmware headers and run the script again."
    )
    h = ["// " + line for line in head.split("\n")]
    h += ["#pragma once", "", "#include <cstdint>", "", "namespace esphome {", "namespace hmi_bms {", ""]
    h += [f"static const uint16_t HMI_PROTOCOL_VERSION = {version};", ""]
    h += ["enum HMIMsgType : uint8_t {"]
    h += [f"  HMI_MSG_{name} = 0x{value:02X}," for name, value in messages.items()]
    h += ["};", "", "enum HMIRegister : uint16_t {"]
    h += [f"  HMI_REG_{name} = 0x{id_:04X}," for name, id_, _, _ in registers]
    h += ["};", "", "enum HMIArray : uint8_t {"]
    h += [f"  HMI_ARRAY_{name} = {value}," for name, value in arrays.items()]
    h += ["};", "", "// BMS event types, in the firmware's order (the index is the type on the wire)"]
    h += ["enum HMIEvent : uint16_t {"]
    h += [f"  HMI_EVENT_{name} = {i}," for i, name in enumerate(events)]
    h += [f"  HMI_EVENT_COUNT = {len(events)},", "};"]
    h += ["static const char *const HMI_EVENT_NAMES[HMI_EVENT_COUNT] = {"]
    h += [f'    "{name}",' for name in events]
    h += ["};", "", "}  // namespace hmi_bms", "}  // namespace esphome", ""]

    py = ['"""' + head + '"""', "", f"PROTOCOL_VERSION = {version}", ""]
    py += ["FLAG_WRITABLE = 0x01", "FLAG_SAVED = 0x02", ""]
    py += ["# name: (id, wire type, flags)", "REGISTERS = {"]
    py += [f'    "{name}": (0x{id_:04X}, 0x{type_:02X}, {flags}),' for name, id_, type_, flags in registers]
    py += ["}", "", "ARRAYS = {"]
    py += [f'    "{name}": {value},' for name, value in arrays.items()]
    py += ["}", "", "# In the firmware's order: the index is the event type on the wire", "EVENT_TYPES = ["]
    py += [f'    "{name}",' for name in events]
    py += ["]", ""]
    return "\n".join(h), "\n".join(py)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    fw = Path(sys.argv[1])
    h, py = render(*parse(fw))
    if "--check" in sys.argv[2:]:
        stale = [p.name for p, text in ((OUT_H, h), (OUT_PY, py))
                 if not p.exists() or read(p) != text]
        if stale:
            sys.exit(f"{', '.join(stale)}: out of date with {fw} (run tools/gen_protocol_map.py)")
        print("protocol map matches the firmware headers")
        return
    OUT_H.write_text(h, encoding="utf-8", newline="\n")
    OUT_PY.write_text(py, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_H.name} and {OUT_PY.name}")


if __name__ == "__main__":
    main()
