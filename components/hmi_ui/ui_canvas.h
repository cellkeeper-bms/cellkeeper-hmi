// The LCD UI's drawing surface: an RGB565 frame and the few shapes the UI is made of, with
// smooth edges and smooth text. Plain C++ with no ESPHome or display code in it, so the same
// code draws on the device and in the PC simulator (sim/).
#pragma once

#include <cstddef>
#include <cstdint>
#include <cstring>

namespace hmiui {

// Colours are written 0xRRGGBB
typedef uint32_t Rgb;

// One character of a font: where its 4-bit alpha bitmap is, and how to place it
struct Glyph {
  uint32_t offset;  // into Font::alpha; each row is (w + 1) / 2 bytes, high nibble first
  uint8_t w, h;
  int8_t left;      // from the pen position to the bitmap's left edge
  int8_t top;       // from the baseline up to the bitmap's top edge
  uint8_t advance;  // how far the pen moves
};

// A font at one size (ui_fonts.h has the ones generated by tools/gen_ui_fonts.py)
struct Font {
  uint8_t size;
  int8_t ascent;        // baseline to the top of a line
  int8_t descent;       // baseline to the bottom of a line
  uint16_t count;
  const uint16_t *codepoints;  // sorted
  const Glyph *glyphs;
  const uint8_t *alpha;
  int line_height() const { return ascent + descent; }
};

enum Align : uint8_t { LEFT, CENTER, RIGHT };

class Canvas {
 public:
  Canvas(uint16_t *pixels, int width, int height) : px_(pixels), w_(width), h_(height) { this->reset_clip(); }

  // A dry run: until end_dry() nothing is drawn. What would have been drawn is summed up in
  // one number instead, so that a frame can be compared with the one before it without
  // drawing either. Drawing a frame costs tens of milliseconds; a dry run costs one or two.
  void begin_dry() {
    dry_ = true;
    sum_ = 2166136261u;
  }
  uint32_t end_dry() {
    dry_ = false;
    return sum_;
  }

  int width() const { return w_; }
  int height() const { return h_; }
  const uint16_t *pixels() const { return px_; }

  // Drawing is limited to this rectangle until it is reset
  void set_clip(int x, int y, int w, int h);
  void reset_clip();

  void clear(Rgb c);
  void fill(int x, int y, int w, int h, Rgb c);
  // alpha 0..255
  void fill_blend(int x, int y, int w, int h, Rgb c, uint8_t alpha);
  // Filled rectangle with rounded corners
  void round_rect(int x, int y, int w, int h, int radius, Rgb c);
  // Outline of a rounded rectangle, `thickness` pixels wide, drawn inside the rectangle
  void round_frame(int x, int y, int w, int h, int radius, int thickness, Rgb c);
  void disc(float cx, float cy, float radius, Rgb c);
  // Part of a ring. Angles in degrees, 0 = right, growing clockwise; drawn from a0 to a1.
  void ring(float cx, float cy, float r_in, float r_out, float a0, float a1, Rgb c, bool round_caps = false);
  void line(float x0, float y0, float x1, float y1, float width, Rgb c);
  void triangle(float x0, float y0, float x1, float y1, float x2, float y2, Rgb c);

  // Text with its line box's top at y. x is the left edge, the centre or the right edge,
  // by `align`. UTF-8; characters the font doesn't have are skipped. Returns the width drawn.
  int text(const Font &font, int x, int y, const char *utf8, Rgb c, Align align = LEFT);
  static int text_width(const Font &font, const char *utf8);

 protected:
  void blend_(int x, int y, uint32_t r, uint32_t g, uint32_t b, uint32_t alpha /* 0..255 */);
  // In a dry run: adds one drawing call with its arguments to the sum, and says "don't draw"
  void sum_up_(uint32_t v) { sum_ = (sum_ ^ v) * 16777619u; }
  static uint32_t bits_(int v) { return (uint32_t) v; }
  static uint32_t bits_(uint32_t v) { return v; }
  static uint32_t bits_(bool v) { return v ? 1u : 0u; }
  static uint32_t bits_(float v) {
    uint32_t u;
    memcpy(&u, &v, sizeof(u));
    return u;
  }
  template<typename... Args> bool dry_call_(uint32_t what, Args... args) {
    if (!dry_) return false;
    this->sum_up_(what);
    (this->sum_up_(bits_(args)), ...);
    return true;
  }
  bool dry_ = false;
  uint32_t sum_ = 0;
  uint16_t *px_;
  int w_, h_;
  int cx0_, cy0_, cx1_, cy1_;  // clip, x1/y1 exclusive
};

// A colour between a (t = 0) and b (t = 1)
inline Rgb mix(Rgb a, Rgb b, float t) {
  t = t < 0.0f ? 0.0f : (t > 1.0f ? 1.0f : t);
  const int ar = (a >> 16) & 0xFF, ag = (a >> 8) & 0xFF, ab = a & 0xFF;
  const int br = (b >> 16) & 0xFF, bg = (b >> 8) & 0xFF, bb = b & 0xFF;
  const int r = ar + (int) ((br - ar) * t + 0.5f), g = ag + (int) ((bg - ag) * t + 0.5f), bl = ab + (int) ((bb - ab) * t + 0.5f);
  return ((Rgb) r << 16) | ((Rgb) g << 8) | (Rgb) bl;
}

inline uint16_t to565(Rgb c) { return (uint16_t) (((c >> 8) & 0xF800) | ((c >> 5) & 0x07E0) | ((c >> 3) & 0x001F)); }
// A 565 pixel as 0xRRGGBB, the way a panel shows it
inline Rgb from565(uint16_t p) {
  const uint32_t r = (p >> 11) & 0x1F, g = (p >> 5) & 0x3F, b = p & 0x1F;
  return ((r << 3 | r >> 2) << 16) | ((g << 2 | g >> 4) << 8) | (b << 3 | b >> 2);
}

}  // namespace hmiui
